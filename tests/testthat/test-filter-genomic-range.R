testthat::test_that("GDS range exclusion respects boundaries and existing filters", {
  path <- tempfile(fileext = ".gds")
  on.exit(unlink(path), add = TRUE)
  file.copy(SeqArray::seqExampleFileName("gds"), path)
  g <- SeqArray::seqOpen(path, readonly = FALSE)
  on.exit(SeqArray::seqClose(g), add = TRUE, after = FALSE)
  ids <- SeqArray::seqGetData(g, "variant.id")
  chrom <- SeqArray::seqGetData(g, "chromosome")
  pos <- SeqArray::seqGetData(g, "position")
  samples <- head(SeqArray::seqGetData(g, "sample.id"), 3)
  target <- which(chrom == chrom[1])
  ends <- range(pos[target[2:5]])
  inside <- ids[chrom == chrom[1] & pos >= ends[1] & pos <= ends[2]]
  prior <- inside[2]
  inactive <- tail(inside, 1)
  meta <- data.frame(VARIANT_ID = ids, FILTERS = ifelse(ids == prior, "earlier", "whitelist"))
  genometranslator::update_genome_gds(g, node.name = "markers.meta", value = meta)
  active <- setdiff(ids, c(inactive, prior))
  SeqArray::seqSetFilter(g, sample.id = samples, variant.id = active, verbose = FALSE)
  testthat::expect_error(filter_genomic_range(g, chrom[1], ends[1]), "both")
  testthat::expect_error(filter_genomic_range(g, "absent"), "Unknown")
  filter_genomic_range(g, chrom[1], ends[1], ends[2], verbose = FALSE)
  after <- genometranslator::extract_markers_metadata(g)
  testthat::expect_setequal(after$VARIANT_ID[after$FILTERS == "filter.genomic.range"],
                            intersect(active, inside))
  testthat::expect_equal(after$FILTERS[match(c(prior, inactive), ids)], c("earlier", "whitelist"))
  testthat::expect_equal(SeqArray::seqGetData(g, "variant.id"), setdiff(active, inside))
  filter_genomic_range(g, chrom[1], verbose = FALSE)
  filter_genomic_range(g, chrom[1], verbose = FALSE)
  testthat::expect_equal(SeqArray::seqGetData(g, "variant.id"), intersect(active, ids[chrom != chrom[1]]))
  testthat::expect_equal(SeqArray::seqGetData(g, "sample.id"), samples)
})
