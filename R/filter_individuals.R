# Filter/blacklist individuals

#' @name filter_individuals

#' @title Filter individuals by sample ID or quality thresholds

#' @description Exclude specified individuals or filter individuals based on:
#' \itemize{
#' \item missingness (genotyping rate)
#' \item heterozygosity
#' \item coverage (total, median, iqr)
#' }
#'
#' **Filter target:** Individuals.
#'
#' \strong{Statistics}: Missingness, heterozygosity and coverage
#'
#' Used internally in \href{https://github.com/thierrygosselin/radr}{radr}
#' and might be of interest for users who wants to blacklist individuals.

#' @param data (2 options) A Genomic Data Structure (GDS)
#' file or object generated by radr.
#'
#' \emph{How to get GDS?}
#' Use \code{\link[genometranslator]{read_genome}} to import supported formats.


#' @param filter.individuals.missing (optional, double) A proportion above which the individuals are
#' blacklisted and removed from the dataset.
#' Default: \code{filter.individuals.missing = NULL}.

#' @param filter.individuals.heterozygosity (optional, string of doubles) A proportion below and
#' above which the individuals are blacklisted and removed from the dataset.
#' Default: \code{filter.individuals.heterozygosity = NULL}.

#' @param filter.individuals.coverage.total Optional numeric threshold(s) or
#'   \code{"outliers"} targeting total coverage per sample. A single numeric
#'   value is the minimum accepted total coverage. Two numeric values specify
#'   the accepted lower and upper limits. \code{"outliers"} derives both limits
#'   from the coverage distribution.
#' Default: \code{filter.individuals.coverage.total = NULL}.

#' @param filter.individuals.coverage.median (optional, string of integers)
#' Target the median coverage per samples.
#' Integers, below and above, that blacklist individuals (removed from the dataset)
#' Default: \code{filter.individuals.coverage.median = NULL}.

#' @param filter.individuals.coverage.iqr (optional, string of integers)
#' Target the IQR (Interquartile Range) coverage per samples.
#' Integers, below and above, that blacklist individuals (removed from the dataset)
#' Default: \code{filter.individuals.coverage.iqr = NULL}.

#' @param blacklist.id Character vector of exact GDS sample IDs or path to a
#'   tab-separated file with one column named \code{INDIVIDUALS}. IDs are read
#'   as text, including any leading zeros. Unknown IDs cause an error. Newly
#'   blacklisted samples are labelled \code{filter.individuals.blacklist} in
#'   the GDS metadata. Previously recorded reasons are retained.
#'   Default: \code{NULL}.
#' @param interactive.filter Logical. By default, the quality-control filters
#'   prompt for thresholds when no blacklist is supplied. With
#'   \code{blacklist.id}, prompts are off unless explicitly enabled in an
#'   interactive R session. Use \code{FALSE} for scripted quality thresholds.
#'
#' @inheritParams radr_common_arguments

#' @section Interactive version:
#' The function applies any supplied \code{blacklist.id} automatically. It then
#' displays missingness, heterozygosity, and coverage diagnostics for the
#' remaining samples and offers the following filters:
#' \enumerate{
#' \item Missingness: asks whether to blacklist samples. If yes, choose the
#' boxplot-outlier statistic or enter the maximum tolerated missing proportion.
#' \item Heterozygosity: asks whether to blacklist samples. If yes, choose the
#' outlier limits or enter the minimum and maximum tolerated heterozygosity.
#' \item Coverage, when available: separately asks whether to filter total,
#' median, and IQR coverage. For every selected statistic, choose the outlier
#' limits or enter minimum and maximum tolerated values.
#' }
#' The initial yes/no prompts are, respectively,
#' \code{"Do you want to blacklist samples based on missingness?"},
#' \code{"... based on heterozygosity?"}, and
#' \code{"... based on TOTAL/MEDIAN/IQR coverage?"}. Choosing custom values
#' leads to the corresponding minimum and maximum threshold questions. Use
#' \code{interactive.filter = FALSE} and explicit arguments for a reproducible
#' analysis.
#'
#' @details A blacklist can be used on its own or with quality thresholds. It
#' is applied before any quality statistics are calculated or thresholds are
#' requested. Newly excluded samples are written to
#' \code{blacklist.individuals.by_id.tsv}. If any samples are newly blacklisted,
#' \code{\link{filter_monomorphic}} checks the remaining samples once, after
#' all individual filters. This also runs for a blacklist-only call.
#'
#' @return The filtered GDS connection. Individual metadata and active samples
#' are updated in place, so the underlying GDS file is modified. Diagnostic
#' files, individual blacklists, and filtering parameters are written to the
#' function output folder.

#' @export
#' @rdname filter_individuals

#' @seealso
#' \code{\link{explore_genomes}}
#' \code{\link[genometranslator]{read_genome}},
#' \code{\link[genometranslator]{tidy_genome}}.

#' @examples
#' \dontrun{
#' genome <- genometranslator::read_genome("my_genome.gds")
#'
#' # Exclude known IDs on a working copy of the GDS.
#' genome <- radr::filter_individuals(
#'   data = "my_genome_copy.gds",
#'   blacklist.id = c("sample_001", "sample_002"),
#'   interactive.filter = FALSE
#' )
#'
#' # Use a TSV with header INDIVIDUALS.
#' genome <- radr::filter_individuals(
#'   data = genome, blacklist.id = "blacklist.tsv", interactive.filter = FALSE
#' )
#'
#' # Apply the blacklist first, then review the remaining samples interactively.
#' genome <- radr::filter_individuals(
#'   data = genome, blacklist.id = "outliers.tsv", interactive.filter = TRUE
#' )
#'
#' # Alternatively, start from a separate unfiltered GDS for a scripted run.
#' scripted_genome <- genometranslator::read_genome("my_genome_scripted.gds")
#' scripted_genome <- radr::filter_individuals(
#'   data = scripted_genome,
#'   interactive.filter = FALSE,
#'   filter.individuals.missing = "outliers",
#'   filter.individuals.heterozygosity = "outliers",
#'   filter.individuals.coverage.total = "outliers"
#' )
#'
#' # Project-specific limits can be supplied instead of outlier rules.
#' another_genome <- genometranslator::read_genome("my_genome_limits.gds")
#' another_genome <- radr::filter_individuals(
#'   data = another_genome,
#'   interactive.filter = FALSE,
#'   filter.individuals.missing = 0.50,
#'   filter.individuals.heterozygosity = c(0.02, 0.06),
#'   filter.individuals.coverage.total = c(9e5, 5e6)
#' )
#' }

#' @author Thierry Gosselin \email{thierrygosselin@@icloud.com}


filter_individuals <- function(
  data,
  interactive.filter = TRUE,
  filter.individuals.missing = NULL,
  filter.individuals.heterozygosity = NULL,
  filter.individuals.coverage.total = NULL,
  filter.individuals.coverage.median = NULL,
  filter.individuals.coverage.iqr = NULL,
  parallel.core = parallel::detectCores() - 1,
  verbose = TRUE,
  ...,
  blacklist.id = NULL
) {

  # Force piped input before printing this function's startup banner.
  force(data)

  ##TESTS
  # path.folder <- NULL
  # parameters <- NULL
  # id.stats <- NULL
  # internal <- FALSE
  # subsample <- NULL
  # subsample.markers.stats <- NULL
  # interactive.filter = TRUE
  # filter.individuals.missing = NULL
  # filter.individuals.heterozygosity = NULL
  # filter.individuals.coverage.total = NULL
  # filter.individuals.coverage.median = NULL
  # filter.individuals.coverage.iqr = NULL
  # parallel.core = parallel::detectCores() - 1
  # verbose = TRUE


  if (!is.null(blacklist.id) && (missing(interactive.filter) || !interactive())) {
    interactive.filter <- FALSE
  }
  run.qc <- interactive.filter ||
    !is.null(filter.individuals.missing) ||
    !is.null(filter.individuals.heterozygosity) ||
    !is.null(filter.individuals.coverage.total) ||
    !is.null(filter.individuals.coverage.median) ||
    !is.null(filter.individuals.coverage.iqr)

  if (run.qc || length(blacklist.id)) {
    if (interactive.filter) verbose <- TRUE
    if (Sys.info()[['sysname']] == "Windows") parallel.core <- 1

    # Common startup -----------------------------------------------------------
    .start <- tgbase::startup(
      package = "radr",
      f.name = "filter_individuals",
      verbose = verbose
    )
    file.date <- .start$file.date
    on.exit(tgbase::teardown(.start), add = TRUE)
    # on.exit(rm(list = setdiff(ls(envir = sys.frame(-1L)), obj.keeper), envir = sys.frame(-1L)))

    # Function call and dotslist -------------------------------------------------
    rad.dots <- radr_dots(
      func.name = as.list(sys.call())[[1]],
      fd = rlang::fn_fmls_names(),
      args.list = as.list(environment()),
      dotslist = rlang::dots_list(..., .homonyms = "error", .check_assign = TRUE),
      keepers = c("path.folder", "parameters", "internal", "id.stats",
                  "subsample", "subsample.markers.stats"),
      verbose = FALSE
    )

    # Checking for missing and/or default arguments ----------------------------
    if (missing(data)) rlang::abort("data is missing")

    # Detect format and validate the blacklist before writing outputs ----------
    data.type <- genometranslator::detect_genomic_format(data)
    if (!data.type %in% c("SeqVarGDSClass", "gds.file")) {
      rlang::abort("Input not supported for this function: read function documentation")
    }
    if (data.type == "gds.file") {
      data <- genometranslator::read_genome(data, verbose = verbose)
      completed <- FALSE
      on.exit(if (!completed) SeqArray::seqClose(data), add = TRUE)
    }
    tgbase::check_package(package = "SeqArray", cran = FALSE, bioc = TRUE)

    if (length(blacklist.id)) {
      blacklist <- .prepare_individual_blacklist(data, blacklist.id)
    }

    # Folders---------------------------------------------------------------------
    path.folder <- generate_folder(
      rad.folder = "filter_individuals",
      path.folder = path.folder,
      internal = internal,
      file.date = file.date,
      verbose = verbose)

    # write the dots file
    tgbase::write_tgbase_tsv(
      data = rad.dots,
      path.folder = path.folder,
      filename = "radr_filter_individuals_args",
      date = TRUE,
      internal = internal,
      write.message = "Function call and arguments stored in: ",
      verbose = verbose
    )


    # Filter parameter file: generate and initiate -----------------------------
    filters.parameters <- filter_parameters(
      generate = TRUE,
      initiate = TRUE,
      update = FALSE,
      parameter.obj = parameters,
      data = data,
      path.folder = path.folder,
      file.date = file.date,
      internal = internal,
      verbose = verbose)

    filter.monomorphic <- FALSE
    if (length(blacklist.id)) {
      removed <- blacklist$metadata[blacklist$exclude, , drop = FALSE]
      if (nrow(removed)) {
        genometranslator::update_genome_gds(
          gds = data, node.name = "individuals.meta",
          value = blacklist$metadata, sync = FALSE
        )
        SeqArray::seqSetFilter(data, sample.id = blacklist$keep, verbose = FALSE)
        filter.monomorphic <- TRUE
        readr::write_tsv(
          removed, file.path(path.folder, "blacklist.individuals.by_id.tsv")
        )
        filters.parameters <- filter_parameters(
          update = TRUE,
          parameter.obj = filters.parameters,
          data = data,
          filter.name = "Filter individuals by ID",
          param.name = "blacklist.id",
          values = paste(length(blacklist$ids), "IDs supplied"),
          path.folder = path.folder,
          file.date = file.date,
          internal = internal,
          verbose = verbose
        )
      }
      if (verbose) message("Newly blacklisted by ID: ", nrow(removed), " individual(s).")
    }

    if (!run.qc) {
      data <- filter_monomorphic(
        data = data, filter.monomorphic = filter.monomorphic,
        parallel.core = parallel.core, verbose = FALSE,
        parameters = filters.parameters, path.folder = path.folder, internal = FALSE
      )
      completed <- TRUE
      return(data)
    }

    # Step 1. Visuals ----------------------------------------------------------
    if (interactive.filter) {
      message("\nInteractive mode: on")
      message("\nStep 1. Visualization of samples QC\n")
    }

    # Note to myself: for now it's better not to subsample, because of filtering
    variant.select <- subsample <- NULL
    subsample.markers.stats <- 1

    id.stats <- genometranslator::generate_stats(
      gds = data,
      individuals = TRUE,
      markers = FALSE,
      exhaustive = TRUE,
      subsample = variant.select,
      path.folder = path.folder,
      file.date = file.date,
      parallel.core = parallel.core,
      verbose = TRUE
    )
    print(id.stats$i.fig)

    # The experimental summary requires total and allele-specific depth.
    qc.depth <- c("COVERAGE_TOTAL", "REF_DEPTH_MEAN", "ALT_DEPTH_MEAN")
    if (all(qc.depth %in% names(id.stats$i.info))) {
      message("\nGenerating suggestions for identifying bad samples: experimental...")
      genometranslator::id_qc_helper(
        x = id.stats$i.info, x.sum = id.stats$i.stats, path.folder = path.folder
      )
    }

    # Step 2. Missingness-----------------------------------------------------------------
    if (interactive.filter) {
      message("\nStep 2. Filtering samples based on individual missingness/genotyping\n")

      filter.individuals.missing <- tgbase::question(
        x = "Do you want to blacklist samples based on missingness ? (y/n):",
        answer.opt = c("y", "n"))

      if (filter.individuals.missing == "y") {
        outlier.stats <- tgbase::question(
          x = "2 options to blacklist samples:\n1. based on the outlier statistics\n2. enter your own threshold", minmax = c(1, 2))
        if (outlier.stats == 1) {
          filter.individuals.missing <- "outliers"
        } else {
          filter.individuals.missing <- tgbase::question(
            x = "Enter the proportion threshold (0-1)
The maximum amount of missingness you tolerate for a sample (e.g. 0.3): ", minmax = c(0, 1))
        }
        outlier.stats <- NULL
      } else {
        filter.individuals.missing <- NULL
      }
    }
    if (!is.null(filter.individuals.missing)) {
      if (!purrr::is_double(filter.individuals.missing)) {
        # if max and outliers high are the same leave the value
        # if max and outliers high are not the same do gymnastic
        if (id.stats$i.stats$OUTLIERS_HIGH[1] == id.stats$i.stats$MAX[1]) {
          higher.eq <- FALSE
        } else {
          higher.eq <- TRUE
        }
        outlier.id.missing <- id.stats$i.stats$OUTLIERS_HIGH[1]
        if (verbose) message("\nRemoving outliers individuals based on genotyping statistics: ", outlier.id.missing)
        filter.individuals.missing <- outlier.id.missing
      } else {
        message("\nRemoving individuals based on genotyping statistics: ", filter.individuals.missing)
        higher.eq <- FALSE
      }

      bl <- dplyr::ungroup(id.stats$i.info)

      if (higher.eq) {
        bl %<>% dplyr::filter(MISSING_PROP >= filter.individuals.missing)
      } else {
        bl %<>% dplyr::filter(MISSING_PROP > filter.individuals.missing)
      }
      bl %<>%
        dplyr::distinct(INDIVIDUALS, .keep_all = TRUE) %>%
        dplyr::mutate(FILTER = "filter.individuals.missing")
      individuals <- genometranslator::extract_individuals_metadata(
        gds = data, whitelist = FALSE
      )
      eligible <- individuals$FILTERS %in% "whitelist"
      bl <- dplyr::filter(bl, INDIVIDUALS %in% individuals$INDIVIDUALS[eligible])
      n.bl <- nrow(bl)

      if (n.bl > 0L) {
        individuals$FILTERS <- as.character(individuals$FILTERS)
        individuals$FILTERS[individuals$INDIVIDUALS %in% bl$INDIVIDUALS] <-
          "filter.individuals.missing"
        genometranslator::update_genome_gds(
          gds = data, node.name = "individuals.meta", value = individuals, sync = FALSE
        )
        SeqArray::seqSetFilter(
          data, sample.id = individuals$INDIVIDUALS[individuals$FILTERS %in% "whitelist"],
          action = "intersect", verbose = FALSE
        )
        filter.monomorphic <- TRUE
        bl.filename <- stringi::stri_join("blacklist.individuals.missing_", file.date, ".tsv")
        readr::write_tsv(x = bl, file = file.path(path.folder, bl.filename))
      }

      # Filter parameter file: update
      filters.parameters <- filter_parameters(
        generate = FALSE,
        initiate = FALSE,
        update = TRUE,
        parameter.obj = filters.parameters,
        data = data,
        filter.name = "Filter individuals based on missingness (with outlier stats or values)",
        param.name = "filter.individuals.missing",
        values = filter.individuals.missing,
        path.folder = path.folder,
        file.date = file.date,
        internal = internal,
        verbose = verbose)

      # results ------------------------------------------------------------------
      radr_results_message(
        rad.message = stringi::stri_join("\nFilter individuals based on missingness: ",
                                         filter.individuals.missing),
        filters.parameters,
        internal,
        verbose
      )
    }#End filter.individuals.missing

    # Step 3. Heterozygosity------------------------------------------------------------
    if (interactive.filter) {
      message("\nStep 3. Filtering samples based on individual heterozygosity\n")

      filter.individuals.heterozygosity <- tgbase::question(
        x = "Do you want to blacklist samples based on heterozygosity ? (y/n):",
        answer.opt = c("y", "n"))

      if (filter.individuals.heterozygosity == "y") {
        outlier.stats <- tgbase::question(
          x = "2 options to blacklist samples:\n1. based on the outlier statistics\n2. enter your own threshold", minmax = c(1, 2))
        if (outlier.stats == 1) {
          filter.individuals.heterozygosity <- "outliers"
        } else {
          filter.individuals.heterozygosity <- c(0,1)
          filter.individuals.heterozygosity[1] <- tgbase::question(
            x = "Enter the min proportion threshold (0-1)
The minimum amount of heterozygosity you tolerate for a sample:", minmax = c(0, 1))
          filter.individuals.heterozygosity[2] <- tgbase::question(
            x = "Enter the max proportion threshold (0-1)
The maximum amount of heterozygosity you tolerate for a sample:", minmax = c(0, 1))
        }
        outlier.stats <- NULL
      } else {
        filter.individuals.heterozygosity <- NULL
      }
    }
    if (!is.null(filter.individuals.heterozygosity)) {
      if (length(filter.individuals.heterozygosity) > 1) {
        het.low <- filter.individuals.heterozygosity[1]
        het.high <- filter.individuals.heterozygosity[2]
        if (verbose) message("\nRemoving individuals based on heterozygosity statistics: ", het.low, " / ", het.high)
        higher.eq <- FALSE
        lower.eq <- FALSE
      } else {
        if (is.character(filter.individuals.heterozygosity)) {
          if (id.stats$i.stats$OUTLIERS_LOW[2] == id.stats$i.stats$MIN[2]) {
            lower.eq <- FALSE
          } else {
            lower.eq <- TRUE
          }
          if (id.stats$i.stats$OUTLIERS_HIGH[2] == id.stats$i.stats$MAX[2]) {
            higher.eq <- FALSE
          } else {
            higher.eq <- TRUE
          }
          het.low <- id.stats$i.stats$OUTLIERS_LOW[2]
          het.high <- id.stats$i.stats$OUTLIERS_HIGH[2]
          if (verbose) message("\nRemoving outliers individuals based on heterozygosity statistics: ", het.low, " / ", het.high)
        } else {
          rlang::abort("Unknown filter.individuals.heterozygosity thresholds used")
        }
      }

      bl <- dplyr::ungroup(id.stats$i.info)

      # fl & fh for filter high and low
      if (lower.eq) {
        fl <- "HETEROZYGOSITY <= het.low"
      } else {
        fl <- "HETEROZYGOSITY < het.low"
      }
      if (higher.eq) {
        fh <- "HETEROZYGOSITY >= het.high"
      } else {
        fh <- "HETEROZYGOSITY > het.high"
      }

      filter.het <- stringi::stri_join(fh, fl, sep = " | ")
      bl %<>%
        dplyr::filter(!!rlang::parse_expr(filter.het)) %>%
        dplyr::distinct(INDIVIDUALS) %>%
        dplyr::mutate(FILTER = "filter.individuals.heterozygosity")
      individuals <- genometranslator::extract_individuals_metadata(
        gds = data, whitelist = FALSE
      )
      eligible <- individuals$FILTERS %in% "whitelist"
      bl <- dplyr::filter(bl, INDIVIDUALS %in% individuals$INDIVIDUALS[eligible])
      n.bl <- nrow(bl)

      if (n.bl > 0L) {
        individuals$FILTERS <- as.character(individuals$FILTERS)
        individuals$FILTERS[individuals$INDIVIDUALS %in% bl$INDIVIDUALS] <-
          "filter.individuals.heterozygosity"
        genometranslator::update_genome_gds(
          gds = data, node.name = "individuals.meta", value = individuals, sync = FALSE
        )
        SeqArray::seqSetFilter(
          data, sample.id = individuals$INDIVIDUALS[individuals$FILTERS %in% "whitelist"],
          action = "intersect", verbose = FALSE
        )
        filter.monomorphic <- TRUE

        # if (verbose) message("    number of individuals blacklisted based on heterozygosity: ", n.bl)
        bl.filename <- stringi::stri_join("blacklist.individuals.heterozygosity_", file.date, ".tsv")
        readr::write_tsv(x = bl, file = file.path(path.folder, bl.filename))
        # bl.i <- update_bl_individuals(gds = data, update = bl)
        id.stats$i.info  %<>%
          dplyr::filter(!INDIVIDUALS %in% bl$INDIVIDUALS)

        # update_radr_gds(gds = data, node.name = "individuals.meta", value = id.stats$info, sync = TRUE)
      }
      # Filter parameter file: update
      filters.parameters <- filter_parameters(
        generate = FALSE,
        initiate = FALSE,
        update = TRUE,
        parameter.obj = filters.parameters,
        data = data,
        filter.name = "Filter individuals based on heterozygosity (with outlier stats or values)",
        param.name = "filter.individuals.heterozygosity",
        values = paste(het.low, het.high, collapse = " / "),
        path.folder = path.folder,
        file.date = file.date,
        internal = internal,
        verbose = verbose)

      # results ------------------------------------------------------------------
      radr_results_message(
        rad.message = stringi::stri_join("\nFilter individuals based on heterozygosity: ", paste(het.low, het.high, collapse = " / ")),
        filters.parameters,
        internal,
        verbose
      )
    }#End filter.individuals.heterozygosity

    # Step 4. Coverage ---------------------------------------------------------
    depth.info <- "total coverage" %in% id.stats$i.stats$GROUP
    if (depth.info) {
      if (interactive.filter) {

        message("\nStep 4. Filtering samples based on individual coverage\n")

        # TOTAL COVERAGE -------------------------------------------------------
        filter.individuals.coverage.total <- tgbase::question(
          x = "Do you want to blacklist samples based on TOTAL coverage ? (y/n):",
          answer.opt = c("y", "n"))

        if (filter.individuals.coverage.total == "y") {
          outlier.stats <- tgbase::question(
            x = "2 options to blacklist samples:\n1. based on the outlier statistics\n2. enter your own threshold", minmax = c(1, 2))
          if (outlier.stats == 1) {
            filter.individuals.coverage.total <- "outliers"
          } else {
            filter.individuals.coverage.total <- c(0,10000000000000000000000)
            filter.individuals.coverage.total[1] <- tgbase::question(
              x = "Enter the minimum TOTAL coverage threshold you tolerate for a sample:",
              minmax = c(0, 10000000000000000000000)
            )
            filter.individuals.coverage.total[2] <- tgbase::question(
              x = "Enter the maximum TOTAL coverage threshold you tolerate for a sample:",
              minmax = c(0, 10000000000000000000000)
              )
          }
          outlier.stats <- NULL
        } else {# if no...
          filter.individuals.coverage.total <- NULL
        }

        # MEDIAN COVERAGE  -----------------------------------------------------
        filter.individuals.coverage.median <- tgbase::question(
          x = "Do you want to blacklist samples based on MEDIAN coverage ? (y/n):",
          answer.opt = c("y", "n")
        )

        if (filter.individuals.coverage.median == "y") {
          outlier.stats <- tgbase::question(
            x = "2 options to blacklist samples:\n1. based on the outlier statistics\n2. enter your own threshold", minmax = c(1, 2))
          if (outlier.stats == 1) {
            filter.individuals.coverage.median <- "outliers"
          } else {
            filter.individuals.coverage.median <- c(0,10000000000000000000000)
            filter.individuals.coverage.median[1] <- tgbase::question(
              x = "Enter the minimum MEDIAN coverage threshold you tolerate for a sample:",
              minmax = c(0, 10000000000000000000000)
              )
            filter.individuals.coverage.median[2] <- tgbase::question(
              x = "Enter the maximum MEDIAN coverage threshold you tolerate for a sample:",
              minmax = c(0, 10000000000000000000000)
              )
          }
          outlier.stats <- NULL
        } else {# if no...
          filter.individuals.coverage.median <- NULL
        }


        # IQR COVERAGE ---------------------------------------------------------
        filter.individuals.coverage.iqr <- tgbase::question(
          x = "Do you want to blacklist samples based on Interquartile Range (IQR) coverage ? (y/n):",
          answer.opt = c("y", "n")
        )

        if (filter.individuals.coverage.iqr == "y") {
          outlier.stats <- tgbase::question(
            x = "2 options to blacklist samples:\n1. based on the outlier statistics\n2. enter your own threshold", minmax = c(1, 2))
          if (outlier.stats == 1) {
            filter.individuals.coverage.iqr <- "outliers"
          } else {
            filter.individuals.coverage.iqr <- c(0,10000000000000000000000)
            filter.individuals.coverage.iqr[1] <- tgbase::question(
              x = "Enter the minimum IQR coverage threshold you tolerate for a sample:",
              minmax = c(0, 10000000000000000000000)
            )
            filter.individuals.coverage.iqr[2] <- tgbase::question(
              x = "Enter the maximum IQR coverage threshold you tolerate for a sample:",
              minmax = c(0, 10000000000000000000000)
            )
          }
          outlier.stats <- NULL
        } else {# if no...
          filter.individuals.coverage.iqr <- NULL
        }

      }#End interactive mode


      # filtering done here...
      # TOTAL COVERAGE -------------------------------------------------------
